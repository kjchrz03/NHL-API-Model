today = pd.to_datetime(date.today())

# ============================================================
# Build DataFrame
# ============================================================
df = pd.DataFrame({
    "season_id": list(season_start_dates.keys()),
    "regular_start": pd.to_datetime(list(season_start_dates.values())),
    "regular_end": pd.to_datetime(list(season_end_dates.values())),
    "thanksgiving_date": pd.to_datetime(list(thanksgiving_dates.values())),
    "playoffs_start": pd.to_datetime(list(playoffs_start.values())),
    "round_2_start": pd.to_datetime(list(round_2_start.values())),
    "round_3_start": pd.to_datetime(list(round_3_start.values())),
    "round_4_start": pd.to_datetime(list(round_4_start.values())),
    "playoffs_end": pd.to_datetime(list(playoffs_end.values())),
})

# ------------------------------------------------------------
# Notes
# ------------------------------------------------------------
df["notes"] = np.where(
    df["season_id"].isin([20122013, 20192020, 20202021]),
    "abbreviated",
    None
)

# ------------------------------------------------------------
# Identify CURRENT season
# ------------------------------------------------------------
df["current_season"] = False

eligible = df[
    (df["regular_start"] <= today) &
    (
        df["playoffs_end"].isna() |
        (df["playoffs_end"] >= today)
    )
]

if not eligible.empty:
    current_season_id = eligible["season_id"].max()
    df.loc[df["season_id"] == current_season_id, "current_season"] = True

    df.loc[
        df["season_id"] == current_season_id,
        "notes"
    ] = (
        df.loc[df["season_id"] == current_season_id, "notes"]
        .fillna("current season")
        .replace("", "current season")
    )

# ============================================================
# Upsert into DuckDB
# ============================================================
con.register("df_season_dates", df)

con.execute("""
CREATE TABLE IF NOT EXISTS important_dates (
    season_id INTEGER,
    regular_start DATE,
    regular_end DATE,
    thanksgiving_date DATE,
    playoffs_start DATE,
    round_2_start DATE,
    round_3_start DATE,
    round_4_start DATE,
    playoffs_end DATE,
    notes VARCHAR,
    current_season BOOLEAN
)
""")

con.execute("""
DELETE FROM important_dates
WHERE season_id IN (SELECT season_id FROM df_season_dates)
""")

con.execute("""
INSERT INTO important_dates
SELECT * FROM df_season_dates
""")

print(
    f"Upserted {len(df)} seasons. "
    f"Current season: {df.loc[df.current_season, 'season_id'].tolist()}"
)

con.close()
print("DuckDB connection closed.")
